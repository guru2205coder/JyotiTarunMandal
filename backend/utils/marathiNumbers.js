export function numberToMarathiWords(num) {
  if (num === null || num === undefined || isNaN(num)) return '';
  num = Math.floor(Number(num));
  if (num === 0) return 'शून्य रुपये फक्त';

  let result = '';

  const crore = Math.floor(num / 10000000);
  num %= 10000000;

  const lakh = Math.floor(num / 100000);
  num %= 100000;

  const thousand = Math.floor(num / 1000);
  num %= 1000;

  const hundred = Math.floor(num / 100);
  const remainder = num % 100;

  if (crore > 0) {
    result += (units[crore] || crore) + ' कोटी ';
  }

  if (lakh > 0) {
    result += (units[lakh] || lakh) + ' लाख ';
  }

  if (thousand > 0) {
    result += (units[thousand] || thousand) + ' हजार ';
  }

  if (hundred > 0) {
    if (hundred === 1) {
      result += 'शंभर ';
    } else {
      result += (units[hundred] || hundred) + 'शे ';
    }
  }

  if (remainder > 0) {
    result += units[remainder] + ' ';
  }

  return result.trim() + ' रुपये फक्त';
}

export function numberToEnglishWords(num) {
  if (num === null || num === undefined || isNaN(num)) return '';
  num = Math.floor(Number(num));
  if (num === 0) return 'Zero Rupees Only';

  const a = [
    '', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten',
    'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'
  ];
  const b = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

  function convertHundreds(n) {
    let str = '';
    if (n > 99) {
      str += a[Math.floor(n / 100)] + ' Hundred ';
      n %= 100;
    }
    if (n > 19) {
      str += b[Math.floor(n / 10)] + (n % 10 > 0 ? ' ' + a[n % 10] : '') + ' ';
    } else if (n > 0) {
      str += a[n] + ' ';
    }
    return str;
  }

  let res = '';
  const crore = Math.floor(num / 10000000);
  num %= 10000000;
  const lakh = Math.floor(num / 100000);
  num %= 100000;
  const thousand = Math.floor(num / 1000);
  num %= 1000;
  const rem = num;

  if (crore > 0) res += convertHundreds(crore) + 'Crore ';
  if (lakh > 0) res += convertHundreds(lakh) + 'Lakh ';
  if (thousand > 0) res += convertHundreds(thousand) + 'Thousand ';
  if (rem > 0) res += convertHundreds(rem);

  return (res.trim() + ' Rupees Only');
}
